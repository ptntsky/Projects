seasons = {'зима': ('грудень', 'січень', 'лютий'), 'весна': ('березень', 'квітень', 'травень'),
           'літо': ('червень', 'липень', 'серпень'), 'осінь': ('вересень', 'жовтень', 'листопад')}
names = 'січень лютий березень квітень травень червень липень серпень вересень жовтень листопад грудень'.split()
num = {m: i for i, m in enumerate(names, 1)}  
rain = {1: 40, 2: 35, 3: 38, 4: 45, 5: 60, 6: 90, 7: 110, 8: 70, 9: 50, 10: 42, 11: 48, 12: 41}
swing = {s: max(rain[num[m]] for m in ms) - min(rain[num[m]] for m in ms) for s, ms in seasons.items()}
print(max(swing, key=swing.get), swing)
